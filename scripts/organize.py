#!/usr/bin/env python3
"""Organize content/Issues into an Obsidian/Enzyme-friendly graph.

Idempotent: safe to re-run after adding new issues.

  python3 scripts/organize.py

For every issue it
  - normalizes frontmatter (title, aliases, year, sections, tags, link count)
  - rewrites links to other issues (devonhdolan.substack.com/p/issue-N) as [[wikilinks]]
  - appends a prev / next / year footer so the issues form a chain in the graph
and it regenerates the hub notes in content/Years/ and content/index.md.
"""

from __future__ import annotations

import re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONTENT = ROOT / "content"
ISSUES = CONTENT / "Issues"
YEARS = CONTENT / "Years"

NAV_START = "%% nav:start — generated by scripts/organize.py %%"
NAV_END = "%% nav:end %%"
FILENAME_RE = re.compile(r"^Issue (\d{3}) - (\d{4}-\d{2}-\d{2})\.md$")
ISSUE_LINK_RE = re.compile(
    r"\[([^\]]*)\]\(https?://devonhdolan\.substack\.com/p/issue-(\d+)[^)\s]*\)"
)
MD_LINK_RE = re.compile(r"\]\(https?://")
SECTIONS = ["Collaborative", "Tech", "Entertainment", "Media", "Spotlight"]


def split_frontmatter(text: str) -> tuple[dict[str, str], str]:
    if not text.startswith("---\n"):
        return {}, text
    end = text.index("\n---\n", 4)
    meta = {}
    for line in text[4:end].splitlines():
        key, sep, value = line.partition(":")
        if sep and not line.startswith((" ", "-")):
            meta[key.strip()] = value.strip()
    return meta, text[end + 5 :]


def yaml_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def strip_nav(body: str) -> str:
    if NAV_START in body:
        body = body[: body.index(NAV_START)]
    return body.rstrip() + "\n"


def main() -> None:
    issues = {}
    for path in sorted(ISSUES.glob("*.md")):
        m = FILENAME_RE.match(path.name)
        if not m:
            print(f"skipping {path.name} (unexpected filename)")
            continue
        issues[int(m.group(1))] = (path, m.group(2))

    numbers = sorted(issues)
    stems = {n: issues[n][0].stem for n in numbers}
    by_year: dict[str, list[dict]] = defaultdict(list)
    rewritten_links = 0

    for i, n in enumerate(numbers):
        path, date = issues[n]
        meta, body = split_frontmatter(path.read_text())
        body = strip_nav(body)

        def to_wikilink(m: re.Match) -> str:
            nonlocal rewritten_links
            target = int(m.group(2))
            if target not in stems:
                return m.group(0)
            rewritten_links += 1
            label = m.group(1).replace("|", "/")
            return f"[[{stems[target]}|{label}]]"

        body = ISSUE_LINK_RE.sub(to_wikilink, body)

        h1 = re.search(r"^# (.+)$", body, re.M)
        title = h1.group(1).strip() if h1 else f"Issue {n}"
        year = date[:4]
        sections = [s for s in SECTIONS if re.search(rf"^## {s}\s*$", body, re.M)]
        links = len(MD_LINK_RE.findall(body))
        era = "relaunch" if meta.get("source", "").strip('"') == "dhd-digest" else "archive"
        tags = [f"year/{year}", f"era/{era}"] + [f"section/{s.lower()}" for s in sections]

        fm = [
            "---",
            f"title: {yaml_str(title)}",
            f"issue: {n}",
            f"date: {date}",
            f"year: {year}",
            f"source: {meta.get('source', yaml_str(''))}",
            "aliases:",
            *[f"  - {yaml_str(a)}" for a in dict.fromkeys([f"Issue {n}", f"Issue {n:03d}"])],
            "sections:" + ("" if sections else " []"),
            *[f"  - {s}" for s in sections],
            "tags:",
            *[f"  - {t}" for t in tags],
            f"links: {links}",
            "---",
        ]

        nav = []
        if i > 0:
            p = numbers[i - 1]
            nav.append(f"← [[{stems[p]}|Issue {p}]]")
        nav.append(f"[[Years/{year}|{year}]]")
        if i + 1 < len(numbers):
            q = numbers[i + 1]
            nav.append(f"[[{stems[q]}|Issue {q}]] →")

        text = "\n".join(fm) + "\n" + body + f"\n{NAV_START}\n\n---\n\n" + " · ".join(nav) + f"\n\n{NAV_END}\n"
        path.write_text(text)

        by_year[year].append(
            {"n": n, "stem": stems[n], "date": date, "title": title, "links": links, "sections": sections}
        )

    YEARS.mkdir(exist_ok=True)
    years = sorted(by_year)
    for y in years:
        rows = by_year[y]
        idx = years.index(y)
        nav = []
        if idx > 0:
            nav.append(f"← [[Years/{years[idx - 1]}|{years[idx - 1]}]]")
        if idx + 1 < len(years):
            nav.append(f"[[Years/{years[idx + 1]}|{years[idx + 1]}]] →")
        lines = [
            "---",
            f'title: "{y}"',
            "tags:",
            "  - hub",
            f"  - year/{y}",
            "---",
            "",
            f"{len(rows)} issues · {sum(r['links'] for r in rows):,} links · [[index|All years]]",
            "",
            "| Issue | Date | Links | Sections |",
            "|---|---|---|---|",
        ]
        for r in rows:
            label = r["title"].replace("|", "/")
            lines.append(
                f"| [[{r['stem']}\\|{label}]] | {r['date']} | {r['links']} | {', '.join(r['sections'])} |"
            )
        if nav:
            lines += ["", " · ".join(nav)]
        (YEARS / f"{y}.md").write_text("\n".join(lines) + "\n")

    total_links = sum(r["links"] for rs in by_year.values() for r in rs)
    index = [
        "---",
        "title: Home",
        "tags:",
        "  - hub",
        "---",
        "",
        "Welcome to my newsletter archive: "
        f"{len(numbers)} issues and {total_links:,} links, from {issues[numbers[0]][1]} to today.",
        "",
        "## By year",
        "",
        *[
            f"- [[Years/{y}|{y}]] — {len(by_year[y])} issues"
            for y in years
        ],
        "",
        "## By section",
        "",
        "Each issue is tagged with the sections it contains:",
        "",
        *[f"- #section/{s.lower()}" for s in SECTIONS],
        "",
        "## Start here",
        "",
        f"- [[{stems[numbers[0]]}|Issue {numbers[0]}]], the first one",
        f"- [[{stems[numbers[-1]]}|Issue {numbers[-1]}]], the latest",
    ]
    (CONTENT / "index.md").write_text("\n".join(index) + "\n")

    print(f"{len(numbers)} issues, {len(years)} year hubs, {rewritten_links} substack links → wikilinks")


if __name__ == "__main__":
    main()
